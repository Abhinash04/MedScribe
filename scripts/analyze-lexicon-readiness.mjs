// What would happen if a symptom lexicon were switched on.
//
// The lexicons ship with `reviewed: false`, so `lexiconFor` returns null and source-side
// recovery does nothing at all. That is deliberate: a wrong mapping here would put a
// symptom on an ADR form that the patient never reported.
//
// This script measures what a native speaker would have to review before that flag
// could be flipped, and it does so by exercising the real matcher — `findingsInSource`
// — against the real dictation corpus, with the lexicon temporarily marked reviewed in
// memory only. Nothing on disk is modified.
//
//   npm run report:lexicon
//
// Four hazards are counted, all of them properties of how the matcher works
// (`haystack.includes(form)`, substring, no word boundaries):
//
//   collision   one native form claimed by two English terms that are not synonyms
//   substring   one form contained inside another, so the shorter always co-fires
//   short       a form so short it will match inside unrelated words
//   unattested  a form that appears nowhere in that language's dictation corpus

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  allLexicons,
  findingsInSource,
  registerLexicon,
} from '../src/constants/symptomLexicon/index.js';
import { samplesFor } from './fixtures/dictation-samples.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));

const MIN_SAFE_LENGTH = 3;

// English terms that mean the same thing may legitimately share one native form.
// Anything outside these groups that shares a form is a collision to review.
const SYNONYM_GROUPS = [
  ['shortness of breath', 'difficulty in breathing', 'difficulty breathing', 'breathing difficulty', 'breathlessness'],
  ['body pain', 'body ache', 'bodyache'],
  ['stomach pain', 'stomach ache', 'abdominal pain', 'tummy pain'],
  ['sore throat', 'throat pain'],
  ['tiredness', 'fatigue', 'exhaustion'],
  ['dizziness', 'giddiness', 'light-headedness'],
  ['loose motions', 'loose motion', 'diarrhoea', 'diarrhea'],
  ['itching', 'itchiness', 'pruritus'],
  ['rash', 'skin rash', 'rashes'],
  ['swelling', 'oedema', 'edema'],
];

const groupOf = term => {
  const key = term.toLowerCase();
  const index = SYNONYM_GROUPS.findIndex(group => group.includes(key));
  return index === -1 ? `solo:${key}` : `group:${index}`;
};

const rows = [];

for (const lexicon of allLexicons()) {
  const code = lexicon.code;
  const entries = Object.entries(lexicon.forms ?? {});
  const forms = [...new Set(entries.flatMap(([, list]) => list ?? []))];

  // -- collisions
  const claimedBy = new Map();
  for (const [term, list] of entries) {
    for (const form of list ?? []) {
      claimedBy.set(form, [...(claimedBy.get(form) ?? []), term]);
    }
  }
  const collisions = [...claimedBy.entries()]
    .filter(([, terms]) => new Set(terms.map(groupOf)).size > 1)
    .map(([form, terms]) => ({ form, terms }));

  // -- substrings
  const substrings = [];
  for (const shorter of forms) {
    for (const longer of forms) {
      if (shorter !== longer && longer.includes(shorter)) {
        substrings.push({ shorter, longer });
      }
    }
  }

  // -- dangerously short
  const short = forms.filter(form => [...form].length < MIN_SAFE_LENGTH);

  // -- attestation, and what recovery would actually fire, measured through the real
  //    matcher with the lexicon marked reviewed in memory only
  const corpus = samplesFor(code) ?? [];
  const corpusText = corpus.map(sample => sample.text).join('\n');
  const attested = forms.filter(form => corpusText.includes(form));

  const wasReviewed = lexicon.reviewed;
  registerLexicon({ ...lexicon, reviewed: true });
  const firings = corpus.map(sample => ({
    id: sample.id,
    found: findingsInSource(sample.text, code),
  }));
  registerLexicon({ ...lexicon, reviewed: wasReviewed });

  const withFindings = firings.filter(firing => firing.found.length);
  const maxFindings = firings.reduce(
    (most, firing) => Math.max(most, firing.found.length),
    0,
  );

  rows.push({
    code,
    reviewed: wasReviewed,
    terms: entries.length,
    forms: forms.length,
    collisions,
    substrings,
    short,
    attested: attested.length,
    corpusSamples: corpus.length,
    samplesThatFire: withFindings.length,
    maxFindings,
    worst: firings.slice().sort((a, b) => b.found.length - a.found.length)[0] ?? null,
  });
}

const total = key => rows.reduce((sum, row) => sum + (row[key]?.length ?? row[key] ?? 0), 0);

const lines = [
  '# Symptom lexicon — readiness report',
  '',
  '_Generated by `npm run report:lexicon`. Do not edit by hand._',
  '',
  '## Status: not activated, and this report does not activate it',
  '',
  'Every lexicon below ships with `reviewed: false`. `lexiconFor()` returns `null` for an',
  'unreviewed lexicon, so `findingsInSource()` returns an empty list and',
  '`reconcileFindings()` adds nothing. Source-side symptom recovery is **inert in the',
  'shipped build**, and `test-source-reconciliation.mjs` (R6.1) holds it that way.',
  '',
  'That is deliberate. A wrong mapping here does not produce a missing field — it',
  'produces a **symptom on an adverse-drug-reaction form that the patient never**',
  '**reported**. The cost of a false positive is not symmetric with the benefit of a',
  'recovered one, so the flag stays off until a native speaker signs each language off.',
  '',
  'The numbers below were measured by exercising the real matcher against the real',
  'dictation corpus with the lexicon marked reviewed **in memory only**. No file was',
  'changed, and no `reviewed:` flag was flipped on disk.',
  '',
  '## What a reviewer would be signing off',
  '',
  '| Language | Reviewed | English terms | Native forms | Attested in corpus | Samples that would fire | Most findings in one sample | Collisions | Substring pairs | Too short |',
  '|---|---|---|---|---|---|---|---|---|---|',
  ...rows.map(
    row =>
      `| \`${row.code}\` | ${row.reviewed ? 'yes' : '**no**'} | ${row.terms} | ${row.forms} ` +
      `| ${row.attested}/${row.forms} | ${row.samplesThatFire}/${row.corpusSamples} ` +
      `| ${row.maxFindings} | ${row.collisions.length} | ${row.substrings.length} | ${row.short.length} |`,
  ),
  '',
  `Across all ${rows.length} drafts: ${total('collisions')} collisions, ` +
    `${total('substrings')} substring pairs, ${total('short')} forms shorter than ` +
    `${MIN_SAFE_LENGTH} characters.`,
  '',
  '## How to read the columns',
  '',
  '- **Attested in corpus** — how many native forms actually appear in that language\'s',
  '  dictations. A form that appears nowhere has never been matched against real speech;',
  '  it was written from a dictionary, not observed. A low fraction here is the single',
  '  strongest argument against activation.',
  '- **Collisions** — one native form claimed by two English terms that are not',
  '  synonyms. The matcher cannot tell them apart, so it will report both. These are',
  '  the entries most likely to put a wrong symptom on a form.',
  '- **Substring pairs** — `findingsInSource` uses `String.includes` with no word',
  '  boundary, so whenever one form is contained in another the shorter one fires too.',
  '  Every pair here is a guaranteed double report, not a risk of one.',
  '- **Too short** — a form of one or two characters will match inside unrelated words.',
  '',
  '## Per-language detail',
  '',
];

for (const row of rows) {
  lines.push(`### \`${row.code}\``, '');
  lines.push(
    `${row.terms} English terms over ${row.forms} native forms. ` +
      `${row.attested} of those forms appear in the corpus; ` +
      `${row.forms - row.attested} do not.`,
    '',
  );

  if (row.collisions.length) {
    lines.push('**Collisions — a reviewer must decide which term each form means:**', '');
    for (const collision of row.collisions.slice(0, 20)) {
      lines.push(`- \`${collision.form}\` is claimed by: ${collision.terms.join(', ')}`);
    }
    if (row.collisions.length > 20) {
      lines.push(`- …and ${row.collisions.length - 20} more`);
    }
    lines.push('');
  } else {
    lines.push('No collisions.', '');
  }

  if (row.substrings.length) {
    lines.push('**Substring pairs — the shorter form always fires with the longer:**', '');
    for (const pair of row.substrings.slice(0, 10)) {
      lines.push(`- \`${pair.shorter}\` inside \`${pair.longer}\``);
    }
    if (row.substrings.length > 10) {
      lines.push(`- …and ${row.substrings.length - 10} more`);
    }
    lines.push('');
  }

  if (row.short.length) {
    lines.push(
      `**Forms shorter than ${MIN_SAFE_LENGTH} characters:** ` +
        row.short.map(form => `\`${form}\``).join(', '),
      '',
    );
  }

  if (row.worst?.found?.length) {
    lines.push(
      `Worst case observed: sample ${row.worst.id} would recover ` +
        `${row.worst.found.length} findings — ${row.worst.found.join(', ')}.`,
      '',
    );
  }
}

lines.push(
  '## What review requires, per language',
  '',
  '1. A clinician who speaks the language reads every English term next to its native',
  '   form and confirms the pairing is what a doctor would actually dictate — not merely',
  '   a correct dictionary translation. The two differ: an earlier attempt seeded Odia',
  '   from Pravah and produced `ଖଞ୍ଜିବା` for itching, where the corpus dictations say',
  '   `କୁଣ୍ଡାଇ`. It matched nothing, 0 of 11.',
  '2. Every collision above is resolved — either the terms are agreed to be synonyms, or',
  '   one of them loses the form.',
  '3. Every substring pair is either accepted as a deliberate hierarchy or separated.',
  '4. Forms with no corpus attestation are either confirmed by the reviewer from their',
  '   own practice, or dropped.',
  '5. Only then does `reviewed: true` go into that one language\'s file, and only that',
  '   language\'s recovery becomes active. The flag is per language on purpose.',
  '',
  '## What activation would still not change',
  '',
  'Even reviewed, recovery stays add-only and low-confidence:',
  '',
  '- it can add a finding the translation dropped; it can never remove or overwrite one',
  '  the translation found (`test-source-reconciliation.mjs` R5.1–R5.3);',
  '- anything it adds drops the field to `CONFIDENCE.FALLBACK`, below the review',
  '  threshold, so the doctor is asked to confirm it (R5.4–R5.6);',
  '- the entry records `origin: \'reconciled\'` and names exactly what was recovered, so',
  '  a recovered symptom is never indistinguishable from a dictated one;',
  '- it does not consult the denial list, which is the strongest single reason it stays',
  '  behind the review gate: a symptom the doctor explicitly denied could be recovered',
  '  from the source and would arrive flagged rather than suppressed (R5.10, R5.11).',
  '',
);

const out = join(HERE, '..', 'docs', 'lexicon-readiness.md');
writeFileSync(out, `${lines.join('\n')}\n`, 'utf8');

console.log(`${rows.length} lexicons, all unreviewed and inert.`);
for (const row of rows) {
  console.log(
    `  ${row.code.padEnd(3)} ${String(row.terms).padStart(3)} terms  ` +
      `${String(row.attested).padStart(3)}/${String(row.forms).padEnd(3)} attested  ` +
      `${String(row.collisions.length).padStart(2)} collisions  ` +
      `${String(row.substrings.length).padStart(2)} substrings`,
  );
}
console.log('wrote docs/lexicon-readiness.md');

// Nothing on disk was changed; prove it.
const untouched = allLexicons().every(lexicon => lexicon.reviewed === false);
if (!untouched) {
  console.error('a lexicon was left marked reviewed — refusing to exit clean');
  process.exit(1);
}
readFileSync(out, 'utf8');
