import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { SYMPTOM_TERMS } from '../src/constants/clinicalCues.js';
import { LANGUAGE_BY_CODE } from '../src/constants/languages.js';
import { translateTexts } from '../src/services/pravah/translationClient.js';
import {
  ERROR_KIND,
  isPravahLanguage,
} from '../src/services/pravah/translationContract.js';
import { CORPUS_LANGUAGES } from './fixtures/dictation-samples.mjs';
import { flag } from './lib/cli-flags.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));

const die = message => {
  console.error(message);
  process.exit(1);
};

const code = flag('lang');
const language = code ? LANGUAGE_BY_CODE[code] : null;

if (!language) {
  die('Pass --lang=<code>, where <code> is a row in src/constants/languages.js.');
}
if (code === 'en') {
  die('English is the reference vocabulary and is not generated.');
}
if (!CORPUS_LANGUAGES.some(entry => entry.code === code)) {
  die(`"${code}" has no voice and no corpus, so it is out of scope for the lexicon.`);
}
if (!isPravahLanguage(language.translationCode)) {
  die(`"${language.translationCode}" is not a language the Pravah API accepts.`);
}

function keyFromServerEnv() {
  try {
    const match = /^PRAVAH_API_KEY=(.*)$/m.exec(
      readFileSync(join(HERE, '..', 'server', '.env'), 'utf8'),
    );
    return match ? match[1].trim() : '';
  } catch {
    return '';
  }
}

const key = process.env.PRAVAH_API_KEY || keyFromServerEnv();
if (!key) {
  die('PRAVAH_API_KEY is not set and server/.env has no value for it.');
}

const BATCH = 20;
const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
const machineTerms = [];

for (let at = 0; at < SYMPTOM_TERMS.length; at += BATCH) {
  const slice = SYMPTOM_TERMS.slice(at, at + BATCH);
  const result = await translateTexts({
    texts: slice,
    to: language.translationCode,
    from: 'en',
    key,
    url: process.env.PRAVAH_API_URL || undefined,
  });

  if (!result.ok) {
    die(
      `Translation failed (${result.errorKind}) on terms ${at + 1}-${at + slice.length}.` +
        (result.errorKind === ERROR_KIND.QUOTA_EXCEEDED
          ? "\nThe key's quota is exhausted; try again after it resets."
          : ''),
    );
  }
  machineTerms.push(...result.texts);
  await sleep(500);
}
const VERBAL_TAIL =
  /\s+(?:होना|आना|हुआ|करना|ହେବା|ହୁଏ|হওয়া|আসা|ஆதல்|అవుతుంది|ಆಗುವುದು|ഉണ്ടാകുക)\s*$/u;

const tidy = value =>
  String(value ?? '')
    .trim()
    .replace(/[.।॥۔?!,;:]+$/u, '')
    .replace(VERBAL_TAIL, '')
    .replace(/^["'“‘](.*)["'”’]$/s, '$1')
    .trim();

const entries = [];
const warnings = [];

SYMPTOM_TERMS.forEach((term, index) => {
  const machine = tidy(machineTerms[index]);

  if (!machine) {
    warnings.push(`${term}: translation came back empty`);
    return;
  }
  if (/^[A-Za-z\s]+$/.test(machine)) {
    warnings.push(`${term}: came back in Latin script — probably untranslated`);
  }
  entries.push({ term, machine });
});

const quote = value => JSON.stringify(String(value));
const lines = entries
  .map(entry => `    ${quote(entry.term)}: [${quote(entry.machine)}],`)
  .join('\n');

const todo = warnings.length
  ? `${warnings.map(warning => `// TODO(${code}): ${warning}`).join('\n')}\n`
  : '';

console.log(`// DRAFT — generated by scripts/seed-symptom-lexicon.mjs.
//
// reviewed: false until a native ${language.englishName} speaker has checked every
// entry. These decide whether a clinical finding is added to an ADR report, so a
// wrong entry reports a symptom the patient does not have. While reviewed is false
// this file is ignored at runtime.
//
// EVERY value below is machine-translated and UNVERIFIED. Each is a list, so a
// reviewer can add the forms actually heard in speech alongside or instead of the
// generated one, and delete anything wrong.
${todo}export default {
  code: ${quote(code)},
  reviewed: false,

  // canonical English finding -> renderings used in this language
  forms: {
${lines}
  },
};`);

console.error(
  `\n${entries.length}/${SYMPTOM_TERMS.length} terms have a draft rendering · ` +
    `${warnings.length} warnings · ALL UNVERIFIED`,
);
for (const warning of warnings) {
  console.error(`  ! ${warning}`);
}
console.error(
  `\nWrite to src/constants/symptomLexicon/${code}.js, register it there, then run:` +
    '\n  npm run test:lexicon',
);
